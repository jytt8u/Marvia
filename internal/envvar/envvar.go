// Пакет envvar читает переменные окружения проекта.
//
// Проект называется Marvia, и переменные называются MARVIA_*. Но панели и
// ноды, поставленные до переименования, запускаются службой, в которой
// прописано прежнее имя — VEIL_*. Молча перестать его понимать значит уронить
// у продавца работающую панель при обновлении: служба стартует, токена нет,
// панель отказывается подниматься.
//
// Поэтому прежнее имя продолжает работать, но каждое обращение к нему пишет в
// журнал строку о том, что пора поправить. Так обновление ничего не ломает, а
// причина разъезда не теряется до того дня, когда поддержку старого имени
// уберут.
package envvar

import (
	"log"
	"os"
	"strings"
	"sync"
)

// oldPrefix и newPrefix — приставки прежнего и нынешнего имени.
const (
	oldPrefix = "VEIL_"
	newPrefix = "MARVIA_"
)

// warned помнит, о какой переменной уже сказано.
//
// Ключ ноды читается на каждом переподключении к панели, и без этого журнал
// заполнился бы одной и той же строкой — а среди неё потерялось бы всё
// остальное.
var warned sync.Map

// Get возвращает значение переменной по нынешнему имени, а если её нет — по
// прежнему. Имя передаётся полностью, с приставкой MARVIA_.
func Get(name string) string {
	if v := os.Getenv(name); v != "" {
		return v
	}

	old := oldName(name)
	if old == "" {
		return ""
	}

	v := os.Getenv(old)
	if v == "" {
		return ""
	}

	if _, said := warned.LoadOrStore(old, true); !said {
		log.Printf("переменная %s устарела: переименуй её в %s, прежнее имя когда-нибудь перестанет работать", old, name)
	}
	return v
}

// oldName переводит нынешнее имя в прежнее. Для имени без нашей приставки
// возвращает пустую строку: подставлять VEIL_ куда попало незачем.
func oldName(name string) string {
	rest, ours := strings.CutPrefix(name, newPrefix)
	if !ours {
		return ""
	}
	return oldPrefix + rest
}
