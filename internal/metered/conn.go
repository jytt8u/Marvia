// Package metered считает байты, прошедшие через соединение.
//
// Считаем на самом внешнем уровне — то, что реально уехало в сеть, вместе с
// добивкой и служебными кадрами. Именно за эти байты платит владелец ноды
// хостеру, значит по ним и надо выставлять лимиты. Считать «полезную
// нагрузку» было бы честнее по отношению к пользователю, но тогда квота
// перестаёт защищать от разорения на трафике.
package metered

import (
	"net"
	"sync/atomic"
	"time"

	"golang.org/x/time/rate"
)

// Conn оборачивает соединение и ведёт счётчики в обе стороны.
//
// Направления названы со стороны ноды: Up — то, что прислал клиент,
// Down — то, что нода отправила клиенту.
type Conn struct {
	net.Conn

	up   atomic.Int64
	down atomic.Int64

	// limiter — потолок скорости. Ставится уже после того, как соединение
	// опознано: до этого неизвестно, чей это аккаунт и какой у него тариф.
	limiter atomic.Pointer[rate.Limiter]
}

// New оборачивает соединение счётчиком.
func New(c net.Conn) *Conn { return &Conn{Conn: c} }

// Limit вешает на соединение потолок скорости. nil снимает его.
//
// Отдельным вызовом, а не полем в New: тариф известен только после проверки
// ключа, а считать байты надо с самого первого — в том числе те, что прислал
// неопознанный гость.
//
// Ограничитель здесь общий на весь аккаунт: клиент держит пул соединений, и
// своё ведро у каждого означало бы кратно больший потолок на деле.
func (c *Conn) Limit(l *rate.Limiter) { c.limiter.Store(l) }

func (c *Conn) Read(p []byte) (int, error) {
	n, err := c.Conn.Read(p)
	if n > 0 {
		c.up.Add(int64(n))
		c.hold(n)
	}
	return n, err
}

func (c *Conn) Write(p []byte) (int, error) {
	// Придерживаем до отправки, а не после: в этом и состоит ограничение
	// скорости. Посчитать уже ушедшее — поздно.
	c.hold(len(p))
	n, err := c.Conn.Write(p)
	if n > 0 {
		c.down.Add(int64(n))
	}
	return n, err
}

// hold придерживает поток, пока скорость выше купленной.
//
// Через ReserveN, а не WaitN: у WaitN своя отмена по контексту, а у нас его
// нет — сроки соединению ставит тот, кто его читает.
//
// Просить больше ведра за раз нельзя: такой ReserveN отказывает и возвращает
// бесконечную задержку, то есть соединение молча повисло бы навсегда. А
// просят: io.Copy отдаёт сюда буфер целиком, и он бывает больше ведра. Поэтому
// берём частями по размеру ведра — на скорость это не влияет, токены всё равно
// копятся с одной и той же частотой.
func (c *Conn) hold(n int) {
	l := c.limiter.Load()
	if l == nil || n <= 0 {
		return
	}

	burst := l.Burst()
	if burst <= 0 {
		return
	}

	for n > 0 {
		take := n
		if take > burst {
			take = burst
		}
		if d := l.ReserveN(time.Now(), take).Delay(); d > 0 {
			time.Sleep(d)
		}
		n -= take
	}
}

// Totals возвращает накопленные счётчики, не сбрасывая их.
func (c *Conn) Totals() (up, down int64) {
	return c.up.Load(), c.down.Load()
}

// Drain забирает накопленное и обнуляет счётчики.
//
// Нужен для периодической выгрузки: держать в памяти абсолютные значения и
// вычитать предыдущие показания — лишний источник ошибок, особенно когда
// выгрузок несколько и они идут параллельно.
func (c *Conn) Drain() (up, down int64) {
	return c.up.Swap(0), c.down.Swap(0)
}
