// Package routes — российские подсети для байпаса.
//
// Зачем это в панели, а не в приложении. Список весит 28 килобайт и меняется
// раз в месяц: зашить его в приложение — значит требовать обновления из
// магазина ради строчки, а магазины у покупателя как раз и отваливаются
// первыми. Панель уже раздаёт подписку и приложения, отдаст и это.
//
// Почему список российский, а не «сайты, которые не работают». Список сайтов
// бесконечен и меняется ежедневно; список адресов страны конечен и меняется
// раз в месяц. Госуслуги, банки и всё государственное живут на российских
// адресах — этого достаточно, чтобы они открывались.
package routes

import (
	"bytes"
	"compress/gzip"
	_ "embed"
	"fmt"
	"io"
	"strings"
	"sync"
)

// ru — подсети из реестра RIPE, собранные командой internal/routes/gen.
//
//go:embed ru.txt.gz
var ru []byte

var (
	once  sync.Once
	list  []string
	fault error
)

// RussianPrefixes отдаёт список подсетей вида 2.56.24.0/22.
//
// Разжимаем один раз и держим в памяти: панель отдаёт этот список каждому
// клиенту при обновлении подписки, а распаковка на каждый запрос — это работа
// ради одного и того же ответа.
func RussianPrefixes() ([]string, error) {
	once.Do(func() {
		zip, err := gzip.NewReader(bytes.NewReader(ru))
		if err != nil {
			fault = fmt.Errorf("список подсетей: %w", err)
			return
		}
		defer zip.Close()

		raw, err := io.ReadAll(zip)
		if err != nil {
			fault = fmt.Errorf("список подсетей: %w", err)
			return
		}

		list = strings.Fields(string(raw))
	})

	return list, fault
}
