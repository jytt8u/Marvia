// Package securedns спрашивает имена у публичного резолвера по HTTPS
// (DNS-over-HTTPS, RFC 8484), и соединение с резолвером идёт через туннель.
//
// Зачем это при уже работающем туннеле. Туннель прячет запросы имён от
// провайдера, но не от ноды: нода расшифровывает VP1, и открытый запрос к
// 1.1.1.1:53 уходит от неё в интернет таким, каким его написало приложение.
// Продавец, у которого стоит нода, видел бы список всех имён, которые
// спрашивает покупатель, — и ему не нужно для этого ничего, кроме tcpdump.
// Через DoH нода видит только TLS-соединение с резолвером: кому, когда и
// сколько байт, но не что внутри.
//
// Почему DoH, а не DNS-over-TLS. Оба шифруют одинаково, и цензор их внутри
// туннеля не видит вовсе. Разница в том, что видит нода и что даёт
// стандартная библиотека. DoT ходит на свой порт 853 — нода по одному номеру
// порта знает, что это имена, — и требует своей сборки потока: очередь
// запросов, сопоставление по ID, переподключения. DoH ходит на 443, как
// обычный HTTPS, а HTTP/2 из net/http сам держит одно соединение на много
// одновременных запросов и сам его поднимает заново. Своего кода с
// криптографией и разбором потока здесь нет ни строчки: TLS и проверку
// сертификата делает crypto/tls против системного хранилища.
package securedns

import (
	"net"
	"net/netip"
	"strings"
)

// Server — публичный резолвер с DoH.
type Server struct {
	// Name — как резолвер называется в журнале.
	Name string

	// Host — имя из сертификата резолвера: по нему идут SNI и проверка
	// сертификата. Само имя мы не разрешаем, см. Addrs.
	Host string

	// Addrs — адреса, к которым подключаемся.
	//
	// Зашиты, а не спрашиваются: спросить адрес резолвера, кроме как у
	// резолвера, не у кого, а спросить у системы — значит выпустить запрос
	// мимо туннеля или открытым через ноду, то есть ровно то, от чего мы
	// уходим. Адреса этих четырёх служб публичны и годами не меняются.
	Addrs []netip.Addr

	// Path — путь запроса, по RFC 8484 обычно /dns-query.
	Path string
}

// Known — резолверы, которые человек выбирает в настройках на телефоне и на
// компьютере. Порядок — тот же, что в выборе: первый — по умолчанию.
var Known = []Server{
	{
		Name:  "Cloudflare",
		Host:  "cloudflare-dns.com",
		Addrs: []netip.Addr{netip.MustParseAddr("1.1.1.1"), netip.MustParseAddr("1.0.0.1")},
		Path:  "/dns-query",
	},
	{
		Name:  "Google",
		Host:  "dns.google",
		Addrs: []netip.Addr{netip.MustParseAddr("8.8.8.8"), netip.MustParseAddr("8.8.4.4")},
		Path:  "/dns-query",
	},
	{
		Name:  "Quad9",
		Host:  "dns.quad9.net",
		Addrs: []netip.Addr{netip.MustParseAddr("9.9.9.9"), netip.MustParseAddr("149.112.112.112")},
		Path:  "/dns-query",
	},
	{
		Name:  "AdGuard",
		Host:  "dns.adguard-dns.com",
		Addrs: []netip.Addr{netip.MustParseAddr("94.140.14.14"), netip.MustParseAddr("94.140.15.15")},
		Path:  "/dns-query",
	},
}

// For отдаёт резолверы для выбранного в настройках адреса: «1.1.1.1» или
// «1.1.1.1:53». Выбранный — первым и с выбранным адресом впереди, остальные
// известные — запасными, в порядке Known.
//
// ok = false — адрес не из известных. Это свой резолвер человека, и как с ним
// говорить по HTTPS, мы не знаем: ни имени для сертификата, ни пути. Такой
// идёт как раньше, открытым DNS через туннель, — и окно об этом говорит.
//
// Запасные — другие службы, а не только второй адрес той же. Цена: человек,
// выбравший AdGuard ради фильтра рекламы, на время недоступности AdGuard
// получит ответы Cloudflare без фильтра. Альтернатива — оставить его без
// имён, то есть без интернета, — хуже, а шифрование при этом не теряется.
func For(address string) ([]Server, bool) {
	host := strings.TrimSpace(address)
	if h, _, err := net.SplitHostPort(host); err == nil {
		host = h
	}
	ip, err := netip.ParseAddr(host)
	if err != nil {
		return nil, false
	}
	ip = ip.Unmap()

	chosen := -1
	for i, s := range Known {
		for _, a := range s.Addrs {
			if a == ip {
				chosen = i
			}
		}
	}
	if chosen < 0 {
		return nil, false
	}

	first := Known[chosen]
	addrs := []netip.Addr{ip}
	for _, a := range first.Addrs {
		if a != ip {
			addrs = append(addrs, a)
		}
	}
	first.Addrs = addrs

	out := []Server{first}
	for i, s := range Known {
		if i != chosen {
			out = append(out, s)
		}
	}
	return out, true
}
