package tunnel

import (
	"errors"
	"net"
	"sync"
)

// Отклик ноды берётся у ядра ОС, а не замером внутри туннеля.
//
// Раньше отклик мерился пингом мультиплексора — кадром, который идёт по тому
// же TCP-соединению, что и трафик. Пока человек что-то качает, в соединении
// стоят мегабайты данных (окно потока — 4 МиБ), и пинг ждёт за ними в
// очереди. На экране это выглядело как скачки отклика до сотен миллисекунд и
// секунд, хотя сеть до ноды была та же. А если очередь держала пинг дольше
// трёх секунд, замер объявлялся неудачным, отклик обнулялся, и уведомление до
// следующего замера показывалось вовсе без него.
//
// У ядра своя оценка: сглаженное время между отправкой сегмента и его
// подтверждением (TCP_INFO). Очередь внутри приложения в неё не входит, а
// очередь в сети — входит, и это честно: её человек и чувствует. Берётся она
// без единого пакета.

// errStalled — соединение с нодой молчит: данные ушли, подтверждений нет.
var errStalled = errors.New("соединение с нодой молчит")

// netConner — обёртка, которая умеет отдать соединение под собой: tls.Conn,
// uTLS, vp1.Conn, дробилка приветствия.
type netConner interface{ NetConn() net.Conn }

// rawTCP спускается по обёрткам до TCP-сокета. nil — его нет: QUIC идёт по
// UDP, а WebSocket нижнего соединения наружу не отдаёт.
func rawTCP(c net.Conn) *net.TCPConn {
	// Глубина с запасом: VP1 поверх REALITY поверх дробилки — три слоя.
	for depth := 0; depth < 8 && c != nil; depth++ {
		if tcp, ok := c.(*net.TCPConn); ok {
			return tcp
		}
		inner, ok := c.(netConner)
		if !ok {
			return nil
		}
		c = inner.NetConn()
	}
	return nil
}

// rttState — что нужно помнить между замерами одного соединения. Linux
// отдаёт время последнего подтверждения и в памяти не нуждается; Windows —
// нет, и обрыв там виден только по разнице двух замеров.
type rttState struct {
	mu       sync.Mutex
	seen     bool
	timeouts uint32
	bytesIn  uint64
}
