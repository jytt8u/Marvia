package vp1

import (
	"encoding/binary"
	"errors"
	"fmt"
	"io"
	"net"
	"sync"
)

// Датаграммы внутри потока.
//
// Зачем это вообще. Долгое время нода умела только TCP, а всё остальное мост
// молча выбрасывал — с расчётом, что приложение поймёт и перейдёт на TCP.
// Расчёт оказался неверным: видео в TikTok, YouTube и Instagram идёт по QUIC,
// то есть по UDP на 443, и приложение не «понимает», а ждёт ответа до
// таймаута, потом пробует ещё раз, и только потом откатывается. Человек видит
// это как «крутится и подгружается», причём на каждом новом ролике заново.
// Замер на живом телефоне: UDP на 443 — четыре секунды тишины.
//
// Почему по одному потоку на поток датаграмм, а не общий канал на всё. Внутри
// мультиплексора поток стоит дёшево, а общий канал потребовал бы тащить адрес
// назначения в каждой датаграмме и самим разбирать, кому пришёл ответ, — то
// есть написать заново то, что мультиплексор уже делает.
//
// Границы датаграмм сохраняются: UDP без них не UDP. Отсюда длина перед
// каждой — поток байтов сам по себе их не хранит.

// MaxDatagram — потолок одной датаграммы.
//
// Больше в UDP не бывает: длина в заголовке занимает два байта. На практике
// всё, что реально летает, помещается в MTU, а крупные ответы имён приходят
// по TCP.
const MaxDatagram = 65535

// datagramBufs — буферы во всю длину датаграммы, общие на процесс.
//
// Поток датаграмм на телефоне заводится на каждый запрос имени и на каждое
// QUIC-соединение, и раньше каждый брал себе три буфера по 64 КиБ — почти
// двести килобайт мусора на один DNS-запрос. Пул отдаёт те же буферы по кругу.
var datagramBufs = sync.Pool{New: func() any { b := make([]byte, 2+MaxDatagram); return &b }}

// DatagramBuffer берёт из пула буфер на датаграмму; вернуть — PutDatagramBuffer.
func DatagramBuffer() *[]byte { return datagramBufs.Get().(*[]byte) }

// PutDatagramBuffer возвращает буфер в пул.
func PutDatagramBuffer(b *[]byte) { datagramBufs.Put(b) }

// WriteDatagram отправляет одну датаграмму с сохранением границы.
func WriteDatagram(w io.Writer, payload []byte) error {
	if len(payload) > MaxDatagram {
		return fmt.Errorf("датаграмма %d байт, больше %d", len(payload), MaxDatagram)
	}

	// Одним Write вместе с длиной: раздельная запись разложила бы заголовок и
	// тело по разным кадрам, и размер датаграмм стал бы виден по таймингам —
	// ровно то, от чего кадры и добиваются.
	// Кадр собирается в буфере из пула: датаграммы QUIC идут тысячами в
	// секунду, и выделять память на каждую — работа сборщику на ровном месте.
	buf := DatagramBuffer()
	defer PutDatagramBuffer(buf)
	frame := (*buf)[:2+len(payload)]
	binary.BigEndian.PutUint16(frame, uint16(len(payload)))
	copy(frame[2:], payload)

	if _, err := w.Write(frame); err != nil {
		return fmt.Errorf("отправка датаграммы: %w", err)
	}
	return nil
}

// ReadDatagram читает одну датаграмму в переданный буфер.
//
// Слишком длинная для буфера датаграмма — это ошибка, а не повод отдать
// половину: половина датаграммы бессмысленна, а остаток хвоста разъехался бы
// по следующим чтениям и сломал бы весь поток.
func ReadDatagram(r io.Reader, buf []byte) (int, error) {
	var head [2]byte
	if _, err := io.ReadFull(r, head[:]); err != nil {
		return 0, err
	}

	size := int(binary.BigEndian.Uint16(head[:]))
	if size > len(buf) {
		return 0, fmt.Errorf("датаграмма %d байт не влезает в буфер %d", size, len(buf))
	}
	if _, err := io.ReadFull(r, buf[:size]); err != nil {
		return 0, fmt.Errorf("чтение датаграммы: %w", err)
	}
	return size, nil
}

// ErrDatagramsUnsupported — нода не понимает запрос датаграмм.
//
// Ноды обновляются не разом с клиентами: их ставит себе продавец, и часть
// какое-то время остаётся со старой версией. Такая нода видит незнакомый тип
// адреса и закрывает поток. Отличать этот случай от «цель недоступна» нужно
// затем, что лечится он по-разному: там подождать, а здесь — навсегда
// вернуться к прежнему поведению до конца сессии.
var ErrDatagramsUnsupported = errors.New("нода не поддерживает датаграммы")

// ErrNodeUnreachable — до ноды не дошли вовсе.
//
// Отличать это от «нода ответила отказом» приходится в двух местах, и в обоих
// цена ошибки высокая.
//
// Первое — надзор за нодой. Отказ ноды по одному адресу означает, что сайт не
// открывается, и менять из-за него ноду нельзя: человек переедет в другую
// страну из-за одной недоступной картинки. Недоступность самой ноды означает
// ровно обратное: не работает ничего, и ждать расписания следующей проверки
// незачем.
//
// Второе — датаграммы. Умирающая нода обрывает поток ровно там же, где старая
// нода отвечает отказом на незнакомый тип адреса. Без этого признака одно
// принимают за другое и выключают датаграммы до конца сессии — из-за того,
// что нода в этот миг умерла.
var ErrNodeUnreachable = errors.New("нода недоступна")

// Datagrams надевает на поток границы датаграмм.
//
// Один Read — одна датаграмма, один Write — одна датаграмма. Обёртка нужна
// обеим сторонам, и нужна именно как net.Conn: иначе границы пришлось бы
// соблюдать вручную в каждом месте, где такой поток используется, а забытое
// место означало бы склеенные пакеты — то есть тихую порчу данных.
func Datagrams(conn net.Conn) net.Conn { return datagramConn{conn} }

type datagramConn struct{ net.Conn }

func (c datagramConn) Read(p []byte) (int, error) {
	return ReadDatagram(c.Conn, p)
}

func (c datagramConn) Write(p []byte) (int, error) {
	if err := WriteDatagram(c.Conn, p); err != nil {
		return 0, err
	}
	return len(p), nil
}
