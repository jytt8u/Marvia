package vp1

import (
	"crypto/rand"
	"encoding/binary"
	"fmt"
	"io"
)

// Замер скорости самой ноды.
//
// Зачем понадобилось. Клиент выбирал ноду по задержке, а задержка и скорость —
// разные вещи. Замер на живом канале: нода в Дубае отвечала за 150 мс и качала
// 8 Мбит/с, нода в Хельсинки — 28 мс и 170 Мбит/с. По задержке разница в пять
// раз, по скорости — в двадцать. Человек чувствует вторую.
//
// Почему данные даёт нода, а не скачивание чего-нибудь снаружи. Скачивание
// мерило бы путь до чужого сервера вместе с ним самим, а нам нужен путь до
// ноды. И оно уводило бы замер в чужие руки: сегодня файл на месте, завтра
// его отдают с другого материка.
//
// Чем это платит продавец. Каждый замер — реальные байты через его канал,
// и за них он платит. Поэтому размер маленький, потолок жёсткий, и клиент
// обязан спрашивать редко, а не при каждом включении.

const (
	// MaxSpeedSample — потолок одного замера.
	//
	// Держится низким намеренно: это не тест скорости канала, а способ
	// отличить хорошую ноду от негодной. Восьмикратную разницу видно и на
	// четверти мегабайта, а платит за неё продавец.
	MaxSpeedSample = 256 << 10

	// DefaultSpeedSample — сколько просим, если не сказано иное.
	//
	// Меньше — и замер выродится в измерение медленного старта TCP: первые
	// килобайты идут не на скорости канала, а на скорости разгона.
	DefaultSpeedSample = 128 << 10
)

// Порядок обмена важен, и на нём это один раз уже заклинило.
//
// Размер уходит вместе с запросом, до ответа ноды. Если отправлять его после
// статуса, обе стороны встанут ждать друг друга: клиент — статус, нода —
// размер. Дедлок ровно посередине замера скорости.
//
//	клиент → адрес с пометкой «замер» + сколько байт просит
//	нода   → статус + сколько отдаст на самом деле
//	нода   → сами байты, ровно столько, сколько обещала

// RequestSample записывает, сколько байт нужно для замера.
func RequestSample(w io.Writer, size int) error {
	if size <= 0 || size > MaxSpeedSample {
		size = DefaultSpeedSample
	}
	return writeSize(w, size, "запрос замера")
}

// ReadSampleRequest читает, сколько байт просят, и обрезает до потолка.
//
// Обрезаем, а не отказываем: просьба сверх потолка — это не злой умысел, а
// клиент новее ноды. Отдать сколько можем полезнее, чем оборвать замер.
func ReadSampleRequest(r io.Reader) (int, error) {
	size, err := readSize(r, "чтение запроса замера")
	if err != nil {
		return 0, err
	}
	if size <= 0 {
		return 0, fmt.Errorf("запрошен замер длиной %d", size)
	}
	return min(size, MaxSpeedSample), nil
}

// GrantSample сообщает клиенту, сколько байт нода отдаст на самом деле.
//
// Без этого клиенту оставалось бы читать до конца потока и верить, что конец
// наступит. Здесь он знает число заранее — и замер не зависит от того, закрыл
// ли собеседник поток и когда.
func GrantSample(w io.Writer, size int) error {
	return writeSize(w, size, "объявление размера замера")
}

// ReadGrant читает, сколько байт нода согласилась отдать.
func ReadGrant(r io.Reader) (int, error) {
	size, err := readSize(r, "чтение размера замера")
	if err != nil {
		return 0, err
	}
	if size <= 0 || size > MaxSpeedSample {
		return 0, fmt.Errorf("нода объявила замер длиной %d", size)
	}
	return size, nil
}

func writeSize(w io.Writer, size int, what string) error {
	var head [4]byte
	binary.BigEndian.PutUint32(head[:], uint32(size))
	if _, err := w.Write(head[:]); err != nil {
		return fmt.Errorf("%s: %w", what, err)
	}
	return nil
}

func readSize(r io.Reader, what string) (int, error) {
	var head [4]byte
	if _, err := io.ReadFull(r, head[:]); err != nil {
		return 0, fmt.Errorf("%s: %w", what, err)
	}
	return int(binary.BigEndian.Uint32(head[:])), nil
}

// WriteSample отдаёт запрошенное число случайных байт.
//
// Случайных, а не нулей. Нули сжимаются и на длинном пути могут поехать не с
// той скоростью, что настоящие данные, — а главное, поток одинаковых байт
// сам по себе примета: настоящий трафик так не выглядит.
func WriteSample(w io.Writer, size int) error {
	const chunk = 32 << 10

	buf := make([]byte, chunk)
	for left := size; left > 0; {
		n := min(left, chunk)
		if _, err := rand.Read(buf[:n]); err != nil {
			return fmt.Errorf("случайные байты: %w", err)
		}
		if _, err := w.Write(buf[:n]); err != nil {
			return fmt.Errorf("отправка замера: %w", err)
		}
		left -= n
	}
	return nil
}
