// Package wintun поднимает и настраивает сетевой интерфейс на Windows.
//
// На телефоне интерфейс выдаёт система, и приложению остаётся отдать
// полученный дескриптор ядру. На Windows такого подарка нет: адаптер надо
// создать драйвером wintun, назначить ему адрес, прописать маршруты и адрес
// для запросов имён — а при выходе всё это аккуратно снять.
//
// Отдельная и самая важная забота — маршрут в обход туннеля до самой ноды.
// Без него соединение с нодой попало бы в тот же туннель, который к этой ноде
// и ведёт, и получился бы круг: клиент ждёт ответа от ноды, а его собственные
// пакеты крутятся внутри него самого.
//
// На других системах пакет пуст. Всё содержимое — в файлах под windows.
